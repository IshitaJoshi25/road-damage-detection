def markdown(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}


def code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.splitlines(keepends=True)}


def build() -> dict:
    cells = [markdown(INTRO), code(SETTINGS), markdown("## 0. Connect Google Drive and check the GPU"), code(SETUP),
             markdown("## Project code\nThese cells write the project files into `/content/proj`.")]
    for rel in EMBEDDED_FILES:
        content = (PROJECT_ROOT / rel).read_text(encoding="utf-8")
        cells.append(code(f"%%writefile {COLAB_PROJECT_DIR}/{rel}\n{content}"))
    cells += [code(COLAB_CONFIG), markdown("## Copy / extract the dataset"), code(EXTRACT),
              markdown("## Install Ultralytics\nColab already has a GPU build of PyTorch."), code(INSTALL)]
    for title, source in PIPELINE:
        cells += [markdown(title), code(source)]
    return {
        "cells": cells,
        "metadata": {
            "accelerator": "GPU",
            "colab": {"provenance": [], "gpuType": "T4"},
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 4,
    }


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(build(), indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(EMBEDDED_FILES)} embedded files)")


if __name__ == "__main__":
    main()
